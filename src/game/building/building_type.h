static inline int32_t building_type_is_temple_complex(int32_t type)
{
    return type >= BUILDING_TEMPLE_COMPLEX_OSIRIS && type <= BUILDING_TEMPLE_COMPLEX_BAST;
}

static inline bool building_type_has_storage(int32_t type)
{
    return type == BUILDING_BAZAAR || type == BUILDING_GRANARY || type == BUILDING_STORAGE_YARD || type == BUILDING_BAZAAR_UP || type == BUILDING_GRANARY_UP ||
        type == BUILDING_STORAGE_YARD_UP;
}

