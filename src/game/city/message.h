typedef struct {
    int32_t param1;
    int32_t param2;
    int16_t year;
    int16_t type;
    int16_t sequence;
    uint8_t is_read;
    uint8_t month;
    int16_t phrases[15];
    uint8_t reserved_1[2];
} city_message;

static_assert(sizeof(city_message) == 0x30, "city_message is a savegame record of 48 bytes");
static_assert(offsetof(city_message, type) == 0x0A && offsetof(city_message, phrases) == 0x10, "city_message is the savegame's layout");

