void sound_city_bind_channel(int32_t building_type, const char *path, int32_t mode)
{
    city_channel *channel = &city_channel_base.types[building_type];
    if (mode == CITY_CHANNEL_ROAM) {
        channel->roam = sound_channel_load_file(path);
    } else if ((mode == CITY_CHANNEL_VARIANT) && (channel->variant_count < CITY_CHANNEL_VARIANTS)) {
        channel->variants[channel->variant_count] = sound_channel_load_file(path);
        channel->variant_count += 1;
    }
}

void sound_city_init_building_channels(void)
{
    for (int32_t i = 0; i < CITY_CHANNEL_TYPES; i++) {
        city_channel *channel = &city_channel_base.types[i];
        for (int32_t j = 0; j < CITY_CHANNEL_VARIANTS; j++) {
            channel->variants[j] = -1;
        }
        channel->roam = -1;
        channel->variant_count = 0;
    }
    for (int32_t i = 0; i < (int32_t) (sizeof(city_binds) / sizeof(city_binds[0])); i++) {
        sound_city_bind_channel(city_binds[i].building_type, city_binds[i].path, city_binds[i].mode);
    }
}
